WITH FT_DOC AS
(
    SELECT PEC.CD_DOCUMENTO, A.CD_MULTI_EMPRESA,
           COUNT(PDC.CD_DOCUMENTO_CLINICO) TOTAL_PREENCHIDO,
           MAX(PDC.DH_CRIACAO) DT_ULTIMO_PREENCHIMENTO,
           MAX(PEC.CD_EDITOR_REGISTRO) ULTIMO_REGISTRO
      FROM DBAMV.PW_DOCUMENTO_CLINICO PDC
      JOIN DBAMV.PW_EDITOR_CLINICO PEC ON PEC.CD_DOCUMENTO_CLINICO = PDC.CD_DOCUMENTO_CLINICO
      JOIN DBAMV.ATENDIME A ON PDC.CD_ATENDIMENTO = A.CD_ATENDIMENTO
      JOIN DBAMV.MULTI_EMPRESAS ME ON A.CD_MULTI_EMPRESA = ME.CD_MULTI_EMPRESA
     WHERE ME.CD_MULTI_EMPRESA IN (3, 4, 7, 10, 11, 25, 63) -- Inclusão da empresa 63
       AND PDC.TP_STATUS IN ('FECHADO', 'ASSINADO')
       AND PDC.DH_CRIACAO >= ADD_MONTHS(SYSDATE, -3)
     GROUP BY PEC.CD_DOCUMENTO, A.CD_MULTI_EMPRESA
)
,
PERFIL AS
(
    SELECT *
    FROM
        (SELECT DISTINCT CD_DOCUMENTO, EMPRESA
         FROM
            (
            --- Documento
            SELECT PMP.NM_VALOR CD_DOCUMENTO, PA.DS_PERFIL_AMBULATORIAL, NVL(PA.CD_MULTI_EMPRESA, PAE.CD_MULTI_EMPRESA) EMPRESA
              FROM PERFIL_AMBULATORIAL PA
              JOIN PW_PERFIL_MODULO PM ON PA.CD_PERFIL_AMBULATORIAL = PM.CD_PERFIL_AMBULATORIAL
              JOIN PW_PERFIL_MODULO_PARAMETRO PMP ON PM.CD_PERFIL_MODULO = PMP.CD_PERFIL_MODULO
              LEFT JOIN PERFIL_AMBULATORIAL_EMPRESA PAE ON PA.CD_PERFIL_AMBULATORIAL = PAE.CD_PERFIL_AMBULATORIAL
             WHERE PMP.CD_PARAMETRO = 'CD_DOCUMENTO'
               AND PA.SN_ATIVO = 'S'
               AND PA.TP_PERFIL = 'SIS'

            UNION ALL
            --- Objeto
            SELECT TB_OBJETO.CD_DOCUMENTO, PA.DS_PERFIL_AMBULATORIAL, NVL(PA.CD_MULTI_EMPRESA, PAE.CD_MULTI_EMPRESA) EMPRESA
              FROM PERFIL_AMBULATORIAL PA
              JOIN PW_PERFIL_MODULO PM ON PA.CD_PERFIL_AMBULATORIAL = PM.CD_PERFIL_AMBULATORIAL
              JOIN PW_PERFIL_MODULO_PARAMETRO PMP ON PM.CD_PERFIL_MODULO = PMP.CD_PERFIL_MODULO
              LEFT JOIN PERFIL_AMBULATORIAL_EMPRESA PAE ON PA.CD_PERFIL_AMBULATORIAL = PAE.CD_PERFIL_AMBULATORIAL
              JOIN (SELECT NM_VALOR CD_DOCUMENTO, TO_CHAR(PTDC.CD_OBJETO) CD_OBJETO
                      FROM PW_TIPO_DOCUMENTO_CONSULTA PTDC
                      JOIN PW_TIPO_DOCUMENTO_MODULO PTDM ON PTDC.CD_TIPO_DOCUMENTO_CONSULTA = PTDM.CD_TIPO_DOCUMENTO_CONSULTA
                      JOIN PW_TIPO_DOCUMENTO_MODULO_PARAM PTDMP ON PTDM.CD_TIPO_DOCUMENTO_MODULO = PTDMP.CD_TIPO_DOCUMENTO_MODULO
                     WHERE PTDMP.CD_PARAMETRO = 'CD_DOCUMENTO') TB_OBJETO ON PMP.NM_VALOR = TB_OBJETO.CD_OBJETO
             WHERE PA.SN_ATIVO = 'S'
               AND PA.TP_PERFIL = 'SIS')
        )
    -- Inclusão do '63' as "P_HR" no PIVOT
    PIVOT (COUNT(EMPRESA) FOR EMPRESA IN ('3' as "P_CSSJ", '4' as "P_HST", '7' as "P_HSC", '10' as "P_HSJ", '11' as "P_HMRP", '25' as "P_HCNSC", '63' as "P_HR"))
)
,
DOC_CONSOLIDADO AS
(
    -- Substituição das antigas DOC, QTD e DATA por uma única leitura
    SELECT CD_DOCUMENTO,
           SUM(TOTAL_PREENCHIDO) AS QTD_TOTAL,
           MAX(DT_ULTIMO_PREENCHIMENTO) AS DT_ULTIMO_GERAL,
           MAX(ULTIMO_REGISTRO) AS ULTIMO_REGISTRO,

           -- Quantidades por Empresa
           SUM(CASE WHEN CD_MULTI_EMPRESA = 7 THEN TOTAL_PREENCHIDO ELSE 0 END) AS QTD_HSC,
           SUM(CASE WHEN CD_MULTI_EMPRESA = 3 THEN TOTAL_PREENCHIDO ELSE 0 END) AS QTD_CSSJ,
           SUM(CASE WHEN CD_MULTI_EMPRESA = 4 THEN TOTAL_PREENCHIDO ELSE 0 END) AS QTD_HST,
           SUM(CASE WHEN CD_MULTI_EMPRESA = 10 THEN TOTAL_PREENCHIDO ELSE 0 END) AS QTD_HSJ,
           SUM(CASE WHEN CD_MULTI_EMPRESA = 11 THEN TOTAL_PREENCHIDO ELSE 0 END) AS QTD_HMRP,
           SUM(CASE WHEN CD_MULTI_EMPRESA = 25 THEN TOTAL_PREENCHIDO ELSE 0 END) AS QTD_HCNSC,
           SUM(CASE WHEN CD_MULTI_EMPRESA = 63 THEN TOTAL_PREENCHIDO ELSE 0 END) AS QTD_HR,

           -- Última Data por Empresa
           MAX(CASE WHEN CD_MULTI_EMPRESA = 7 THEN DT_ULTIMO_PREENCHIMENTO END) AS DT_ULTIMO_HSC,
           MAX(CASE WHEN CD_MULTI_EMPRESA = 3 THEN DT_ULTIMO_PREENCHIMENTO END) AS DT_ULTIMO_CSSJ,
           MAX(CASE WHEN CD_MULTI_EMPRESA = 4 THEN DT_ULTIMO_PREENCHIMENTO END) AS DT_ULTIMO_HST,
           MAX(CASE WHEN CD_MULTI_EMPRESA = 10 THEN DT_ULTIMO_PREENCHIMENTO END) AS DT_ULTIMO_HSJ,
           MAX(CASE WHEN CD_MULTI_EMPRESA = 11 THEN DT_ULTIMO_PREENCHIMENTO END) AS DT_ULTIMO_HMRP,
           MAX(CASE WHEN CD_MULTI_EMPRESA = 25 THEN DT_ULTIMO_PREENCHIMENTO END) AS DT_ULTIMO_HCNSC,
           MAX(CASE WHEN CD_MULTI_EMPRESA = 63 THEN DT_ULTIMO_PREENCHIMENTO END) AS DT_ULTIMO_HR
    FROM FT_DOC
    GROUP BY CD_DOCUMENTO
)
,
VERSAO AS
(
    -- Transformado em CTE para deixar o SELECT final mais limpo
    SELECT CD_DOCUMENTO, MAX(VL_VERSAO) VERSAO
    FROM EDITOR.EDITOR_VERSAO_DOCUMENTO
    WHERE SN_ATIVO = '1'
      GROUP BY CD_DOCUMENTO
)

SELECT CAST(ED.CD_DOCUMENTO AS NUMBER) CÓDIGO,
       UPPER(ED.DS_DOCUMENTO) AS NOME,
     ----  UPPER(ED.DS_IDENTIFICADOR) AS DS_IDENTIFICADOR,
       V.VERSAO,

       NVL(P.P_HSC, 0) HSC,
       NVL(P.P_CSSJ, 0) CSSJ,
       NVL(P.P_HST, 0) HST,
       NVL(P.P_HSJ, 0) HSJ,
       NVL(P.P_HMRP, 0) HMRP,
       NVL(P.P_HCNSC, 0) HCNSC,
       NVL(P.P_HR, 0) HR,

       DC.QTD_HSC as "Uso HSC",
       DC.QTD_CSSJ as "Uso CSSJ",
       DC.QTD_HST as "Uso HST",
       DC.QTD_HSJ as "Uso HSJ",
       DC.QTD_HMRP as "Uso HMRP",
       DC.QTD_HCNSC as "Uso HCNSC",
       DC.QTD_HR as "Uso HR",
       DC.QTD_TOTAL as "Total",

       DC.DT_ULTIMO_HSC  as "Ult. HSC",
       DC.DT_ULTIMO_CSSJ as "Ult. CSSJ",
       DC.DT_ULTIMO_HST as "Ult. HST",
       DC.DT_ULTIMO_HSJ  as "Ult. HSJ",
       DC.DT_ULTIMO_HMRP as "Ult. HMRP",
       DC.DT_ULTIMO_HCNSC as "Ult. HCNSC",
       DC.DT_ULTIMO_HR as "Ult. HR",
       DC.DT_ULTIMO_GERAL as "Ult. Geral",

       DC.ULTIMO_REGISTRO as "Ult. Registro"

FROM EDITOR.EDITOR_DOCUMENTO ED
LEFT JOIN DOC_CONSOLIDADO DC ON TO_CHAR(DC.CD_DOCUMENTO) = TO_CHAR(ED.CD_DOCUMENTO)
LEFT JOIN PERFIL P ON TO_CHAR(P.CD_DOCUMENTO) = TO_CHAR(ED.CD_DOCUMENTO)
LEFT JOIN VERSAO V ON TO_CHAR(V.CD_DOCUMENTO) = TO_CHAR(ED.CD_DOCUMENTO)
WHERE ED.CD_TIPO_ITEM = 13
--AND DC.CD_DOCUMENTO = 1050

ORDER BY NVL(DC.QTD_TOTAL, 0) DESC;



