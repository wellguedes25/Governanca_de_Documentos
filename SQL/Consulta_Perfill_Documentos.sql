-- Bloco 1: Vínculo Direto (Documento)
SELECT PMP.NM_VALOR AS CD_DOCUMENTO,
       PM.NM_TITULO,
       PA.DS_PERFIL_AMBULATORIAL,
      Decode(NVL(PA.CD_MULTI_EMPRESA, PAE.CD_MULTI_EMPRESA),3, 'CSSJ',4,'HST',7,'HSC',10,'HSJ',11,'HMRP',25,'HCNSC',63,'HR') AS EMPRESA
  FROM PERFIL_AMBULATORIAL PA
  JOIN PW_PERFIL_MODULO PM ON PA.CD_PERFIL_AMBULATORIAL = PM.CD_PERFIL_AMBULATORIAL
  JOIN PW_PERFIL_MODULO_PARAMETRO PMP ON PM.CD_PERFIL_MODULO = PMP.CD_PERFIL_MODULO
  LEFT JOIN PERFIL_AMBULATORIAL_EMPRESA PAE ON PA.CD_PERFIL_AMBULATORIAL = PAE.CD_PERFIL_AMBULATORIAL
 WHERE PMP.CD_PARAMETRO = 'CD_DOCUMENTO'
   AND PA.SN_ATIVO = 'S'
   AND PA.TP_PERFIL = 'SIS'
   AND PMP.NM_VALOR = '1050' --:CD_DOCUMENTO

UNION ALL

-- Bloco 2: Vínculo Indireto (Objeto)
SELECT TB_OBJETO.CD_DOCUMENTO,
       PM.NM_TITULO,
       PA.DS_PERFIL_AMBULATORIAL,
      Decode(NVL(PA.CD_MULTI_EMPRESA, PAE.CD_MULTI_EMPRESA),3, 'CSSJ',4,'HST',7,'HSC',10,'HSJ',11,'HMRP',25,'HCNSC',63,'HR') AS EMPRESA
  FROM PERFIL_AMBULATORIAL PA
  JOIN PW_PERFIL_MODULO PM ON PA.CD_PERFIL_AMBULATORIAL = PM.CD_PERFIL_AMBULATORIAL
  JOIN PW_PERFIL_MODULO_PARAMETRO PMP ON PM.CD_PERFIL_MODULO = PMP.CD_PERFIL_MODULO
  LEFT JOIN PERFIL_AMBULATORIAL_EMPRESA PAE ON PA.CD_PERFIL_AMBULATORIAL = PAE.CD_PERFIL_AMBULATORIAL

  -- Subconsulta com JOIN explicito e filtro adicionado
  JOIN (SELECT NM_VALOR AS CD_DOCUMENTO, TO_CHAR(PTDC.CD_OBJETO) AS CD_OBJETO
          FROM PW_TIPO_DOCUMENTO_CONSULTA PTDC
          JOIN PW_TIPO_DOCUMENTO_MODULO PTDM ON PTDC.CD_TIPO_DOCUMENTO_CONSULTA = PTDM.CD_TIPO_DOCUMENTO_CONSULTA
          JOIN PW_TIPO_DOCUMENTO_MODULO_PARAM PTDMP ON PTDM.CD_TIPO_DOCUMENTO_MODULO = PTDMP.CD_TIPO_DOCUMENTO_MODULO
         WHERE PTDMP.CD_PARAMETRO = 'CD_DOCUMENTO'
           AND NM_VALOR = '1050' --:CD_DOCUMENTO
       ) TB_OBJETO ON PMP.NM_VALOR = TB_OBJETO.CD_OBJETO

 WHERE PA.SN_ATIVO = 'S'
   AND PA.TP_PERFIL = 'SIS'