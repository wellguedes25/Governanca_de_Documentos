-- Consulta principal para a página de Similaridade
-- Obtém os dados da tabela processada pelo motor de PLN
SELECT 
    CD_ATENDIMENTO as ATENDIMENTO,
    CD_DOCUMENTO as DOCUMENTO,
    DS_DOCUMENTO as NOME_DOCUMENTO,
    IDENTIFICADOR_FILTRO as IDENTIFICADOR,
    DH_FECHAMENTO as DATA_HORA,
    CD_PRESTADOR as PRESTADOR,
    LEITO,
    UNIDADE,
    GRAU_SIMILARIDADE as SCORE
FROM 
    DBAMV.TB_AUDITORIA_SIMILARIDADE
ORDER BY 
    DH_FECHAMENTO DESC;

-- Consulta para o drill-down de comparação
-- Obtém os textos originais e anteriores para comparação lado a lado
SELECT 
    DBMS_LOB.SUBSTR(ERC.LO_VALOR, 4000, 1) AS TEXTO_ATUAL,
    LAG(DBMS_LOB.SUBSTR(ERC.LO_VALOR, 4000, 1)) OVER (
        PARTITION BY ATE.CD_PACIENTE, ECA.CD_CAMPO
        ORDER BY PDC.DH_FECHAMENTO
    ) AS TEXTO_ANTERIOR
FROM
    DBAMV.PW_DOCUMENTO_CLINICO PDC
INNER JOIN DBAMV.PW_EDITOR_CLINICO PEC ON PEC.CD_DOCUMENTO_CLINICO = PDC.CD_DOCUMENTO_CLINICO
INNER JOIN DBAMV.EDITOR_REGISTRO_CAMPO ERC ON ERC.CD_REGISTRO = PEC.CD_EDITOR_REGISTRO
INNER JOIN DBAMV.EDITOR_CAMPO ECA ON ECA.CD_CAMPO = ERC.CD_CAMPO
INNER JOIN DBAMV.ATENDIME ATE ON ATE.CD_ATENDIMENTO = PDC.CD_ATENDIMENTO
WHERE
    PEC.CD_DOCUMENTO = :CD_DOCUMENTO;
