------------------------------------------------------------------------- */

-- 1.1 CARD: TOTAL GERAL DE PREENCHIMENTOS (90 DIAS)
SELECT /*+ PARALLEL(4) */ COUNT(1) AS TOTAL_GERAL_PREENCHIDO
  FROM DBAMV.PW_DOCUMENTO_CLINICO PDC
  JOIN DBAMV.PW_EDITOR_CLINICO PEC ON PEC.CD_DOCUMENTO_CLINICO = PDC.CD_DOCUMENTO_CLINICO
  JOIN EDITOR_DOCUMENTO ED ON ED.CD_DOCUMENTO = PEC.CD_DOCUMENTO
  JOIN DBAMV.ATENDIME A ON PDC.CD_ATENDIMENTO = A.CD_ATENDIMENTO
 WHERE PDC.DH_CRIACAO >= TRUNC(SYSDATE) - 90
   AND PDC.TP_STATUS IN ('FECHADO', 'ASSINADO')
   AND A.CD_MULTI_EMPRESA IN (3, 4, 7, 10, 11, 25, 63)
   AND ED.CD_TIPO_ITEM = 13;

-- 1.2 GRÁFICO: TOP 10 DOCUMENTOS MAIS UTILIZADOS (CURVA ABC)
SELECT * FROM (
    SELECT /*+ PARALLEL(4) */
           CAST(ED.CD_DOCUMENTO AS NUMBER) AS CD_DOCUMENTO,
           UPPER(ED.DS_DOCUMENTO) AS DS_DOCUMENTO,
           COUNT(1) AS QTD_TOTAL
      FROM DBAMV.PW_DOCUMENTO_CLINICO PDC
      JOIN DBAMV.PW_EDITOR_CLINICO PEC ON PEC.CD_DOCUMENTO_CLINICO = PDC.CD_DOCUMENTO_CLINICO
      JOIN EDITOR_DOCUMENTO ED ON ED.CD_DOCUMENTO = PEC.CD_DOCUMENTO
      JOIN DBAMV.ATENDIME A ON PDC.CD_ATENDIMENTO = A.CD_ATENDIMENTO
     WHERE A.CD_MULTI_EMPRESA IN (3, 4, 7, 10, 11, 25, 63)
       AND PDC.TP_STATUS IN ('FECHADO', 'ASSINADO')
       AND ED.CD_TIPO_ITEM = 13
       AND PDC.DH_CRIACAO >= TRUNC(SYSDATE) - 90
     GROUP BY CAST(ED.CD_DOCUMENTO AS NUMBER), UPPER(ED.DS_DOCUMENTO)
     ORDER BY QTD_TOTAL DESC
) WHERE ROWNUM <= 10;

-- 1.3 CARD: TOTAL DE DOCUMENTOS OCIOSOS (ZERO USO EM 90 DIAS)
WITH FT_DOC_USO AS (
    SELECT /*+ PARALLEL(4) */ PEC.CD_DOCUMENTO
      FROM DBAMV.PW_DOCUMENTO_CLINICO PDC
      JOIN DBAMV.PW_EDITOR_CLINICO PEC ON PEC.CD_DOCUMENTO_CLINICO = PDC.CD_DOCUMENTO_CLINICO
      JOIN DBAMV.ATENDIME A ON PDC.CD_ATENDIMENTO = A.CD_ATENDIMENTO
     WHERE A.CD_MULTI_EMPRESA IN (3, 4, 7, 10, 11, 25, 63)
       AND PDC.TP_STATUS IN ('FECHADO', 'ASSINADO')
       AND PDC.DH_CRIACAO >= TRUNC(SYSDATE) - 90
     GROUP BY PEC.CD_DOCUMENTO
)
SELECT COUNT(1) AS TOTAL_DOCS_OCIOSOS
  FROM EDITOR_DOCUMENTO ED
  LEFT JOIN FT_DOC_USO F ON F.CD_DOCUMENTO = ED.CD_DOCUMENTO
 WHERE ED.CD_TIPO_ITEM = 13
   AND F.CD_DOCUMENTO IS NULL;


/* -------------------------------------------------------------------------
   BLOCO 2: ADESÃO POR UNIDADE (MULTI-EMPRESA)
------------------------------------------------------------------------- */

-- 2.1 RANKING: VOLUME DE PREENCHIMENTOS POR UNIDADE
SELECT /*+ PARALLEL(4) */
       A.CD_MULTI_EMPRESA,
       CASE A.CD_MULTI_EMPRESA
            WHEN 3 THEN 'CSSJ' WHEN 4 THEN 'HST' WHEN 7 THEN 'HSC'
            WHEN 10 THEN 'HSJ' WHEN 11 THEN 'HMRP' WHEN 25 THEN 'HCNSC'
            WHEN 63 THEN 'HR'
       END AS SIGLA_UNIDADE,
       COUNT(1) AS QTD_TOTAL_PREENCHIDA
  FROM DBAMV.PW_DOCUMENTO_CLINICO PDC
  JOIN DBAMV.PW_EDITOR_CLINICO PEC ON PEC.CD_DOCUMENTO_CLINICO = PDC.CD_DOCUMENTO_CLINICO
  JOIN EDITOR_DOCUMENTO ED ON ED.CD_DOCUMENTO = PEC.CD_DOCUMENTO
  JOIN DBAMV.ATENDIME A ON PDC.CD_ATENDIMENTO = A.CD_ATENDIMENTO
 WHERE A.CD_MULTI_EMPRESA IN (3, 4, 7, 10, 11, 25, 63)
   AND PDC.TP_STATUS IN ('FECHADO', 'ASSINADO')
   AND ED.CD_TIPO_ITEM = 13
   AND PDC.DH_CRIACAO >= TRUNC(SYSDATE) - 90
 GROUP BY A.CD_MULTI_EMPRESA
 ORDER BY QTD_TOTAL_PREENCHIDA DESC;

-- 2.2 ALERTA: DIAS SEM USO POR UNIDADE (ORDENADO PELOS MAIS CRÍTICOS)
SELECT /*+ PARALLEL(4) */
       CAST(ED.CD_DOCUMENTO AS NUMBER) AS CD_DOCUMENTO,
       UPPER(ED.DS_DOCUMENTO) AS DS_DOCUMENTO,
       CASE A.CD_MULTI_EMPRESA
            WHEN 3 THEN 'CSSJ' WHEN 4 THEN 'HST' WHEN 7 THEN 'HSC'
            WHEN 10 THEN 'HSJ' WHEN 11 THEN 'HMRP' WHEN 25 THEN 'HCNSC'
            WHEN 63 THEN 'HR'
       END AS SIGLA_UNIDADE,
       MAX(PDC.DH_CRIACAO) AS ULTIMA_DATA_USO,
       TRUNC(SYSDATE) - TRUNC(MAX(PDC.DH_CRIACAO)) AS DIAS_SEM_USO
  FROM DBAMV.PW_DOCUMENTO_CLINICO PDC
  JOIN DBAMV.PW_EDITOR_CLINICO PEC ON PEC.CD_DOCUMENTO_CLINICO = PDC.CD_DOCUMENTO_CLINICO
  JOIN EDITOR_DOCUMENTO ED ON ED.CD_DOCUMENTO = PEC.CD_DOCUMENTO
  JOIN DBAMV.ATENDIME A ON PDC.CD_ATENDIMENTO = A.CD_ATENDIMENTO
 WHERE A.CD_MULTI_EMPRESA IN (3, 4, 7, 10, 11, 25, 63)
   AND PDC.TP_STATUS IN ('FECHADO', 'ASSINADO')
   AND ED.CD_TIPO_ITEM = 13
   AND PDC.DH_CRIACAO >= TRUNC(SYSDATE) - 90
 GROUP BY CAST(ED.CD_DOCUMENTO AS NUMBER), UPPER(ED.DS_DOCUMENTO), A.CD_MULTI_EMPRESA
 ORDER BY DIAS_SEM_USO DESC;


