-- 3.1 AUDITORIA: QUANTIDADE DE PERFIS AMBULATORIAIS POR DOCUMENTO
WITH PERFIL_DOC AS (
    SELECT /*+ PARALLEL(4) */ PMP.NM_VALOR AS CD_DOCUMENTO, PA.CD_PERFIL_AMBULATORIAL
      FROM PERFIL_AMBULATORIAL PA
      JOIN PW_PERFIL_MODULO PM ON PA.CD_PERFIL_AMBULATORIAL = PM.CD_PERFIL_AMBULATORIAL
      JOIN PW_PERFIL_MODULO_PARAMETRO PMP ON PM.CD_PERFIL_MODULO = PMP.CD_PERFIL_MODULO
     WHERE PMP.CD_PARAMETRO = 'CD_DOCUMENTO' AND PA.SN_ATIVO = 'S' AND PA.TP_PERFIL = 'SIS'
    UNION
    SELECT /*+ PARALLEL(4) */ TB_OBJETO.CD_DOCUMENTO, PA.CD_PERFIL_AMBULATORIAL
      FROM PERFIL_AMBULATORIAL PA
      JOIN PW_PERFIL_MODULO PM ON PA.CD_PERFIL_AMBULATORIAL = PM.CD_PERFIL_AMBULATORIAL
      JOIN PW_PERFIL_MODULO_PARAMETRO PMP ON PM.CD_PERFIL_MODULO = PMP.CD_PERFIL_MODULO
      JOIN (SELECT NM_VALOR AS CD_DOCUMENTO, TO_CHAR(PTDC.CD_OBJETO) AS CD_OBJETO
              FROM PW_TIPO_DOCUMENTO_CONSULTA PTDC
              JOIN PW_TIPO_DOCUMENTO_MODULO PTDM ON PTDC.CD_TIPO_DOCUMENTO_CONSULTA = PTDM.CD_TIPO_DOCUMENTO_CONSULTA
              JOIN PW_TIPO_DOCUMENTO_MODULO_PARAM PTDMP ON PTDM.CD_TIPO_DOCUMENTO_MODULO = PTDMP.CD_TIPO_DOCUMENTO_MODULO
             WHERE PTDMP.CD_PARAMETRO = 'CD_DOCUMENTO'
           ) TB_OBJETO ON PMP.NM_VALOR = TB_OBJETO.CD_OBJETO
     WHERE PA.SN_ATIVO = 'S' AND PA.TP_PERFIL = 'SIS'
)
SELECT /*+ PARALLEL(4) */
       CAST(ED.CD_DOCUMENTO AS NUMBER) AS CD_DOCUMENTO,
       UPPER(ED.DS_DOCUMENTO) AS DS_DOCUMENTO,
       COUNT(1) AS QTD_PERFIS_VINCULADOS
  FROM EDITOR_DOCUMENTO ED
  JOIN PERFIL_DOC PD ON TO_CHAR(ED.CD_DOCUMENTO) = PD.CD_DOCUMENTO
 WHERE ED.CD_TIPO_ITEM = 13
 GROUP BY CAST(ED.CD_DOCUMENTO AS NUMBER), UPPER(ED.DS_DOCUMENTO)
 ORDER BY QTD_PERFIS_VINCULADOS DESC;

-- 3.2 CARD: TOTAL DE DOCUMENTOS ÓRFÃOS (SEM PERFIL DE ACESSO VINCULADO)
WITH PERFIL_DOC AS (
    SELECT /*+ PARALLEL(4) */ PMP.NM_VALOR AS CD_DOCUMENTO
      FROM PERFIL_AMBULATORIAL PA
      JOIN PW_PERFIL_MODULO PM ON PA.CD_PERFIL_AMBULATORIAL = PM.CD_PERFIL_AMBULATORIAL
      JOIN PW_PERFIL_MODULO_PARAMETRO PMP ON PM.CD_PERFIL_MODULO = PMP.CD_PERFIL_MODULO
     WHERE PMP.CD_PARAMETRO = 'CD_DOCUMENTO' AND PA.SN_ATIVO = 'S' AND PA.TP_PERFIL = 'SIS'
    UNION
    SELECT /*+ PARALLEL(4) */ TB_OBJETO.CD_DOCUMENTO
      FROM PERFIL_AMBULATORIAL PA
      JOIN PW_PERFIL_MODULO PM ON PA.CD_PERFIL_AMBULATORIAL = PM.CD_PERFIL_AMBULATORIAL
      JOIN PW_PERFIL_MODULO_PARAMETRO PMP ON PM.CD_PERFIL_MODULO = PMP.CD_PERFIL_MODULO
      JOIN (SELECT NM_VALOR AS CD_DOCUMENTO, TO_CHAR(PTDC.CD_OBJETO) AS CD_OBJETO
              FROM PW_TIPO_DOCUMENTO_CONSULTA PTDC
              JOIN PW_TIPO_DOCUMENTO_MODULO PTDM ON PTDC.CD_TIPO_DOCUMENTO_CONSULTA = PTDM.CD_TIPO_DOCUMENTO_CONSULTA
              JOIN PW_TIPO_DOCUMENTO_MODULO_PARAM PTDMP ON PTDM.CD_TIPO_DOCUMENTO_MODULO = PTDMP.CD_TIPO_DOCUMENTO_MODULO
             WHERE PTDMP.CD_PARAMETRO = 'CD_DOCUMENTO'
           ) TB_OBJETO ON PMP.NM_VALOR = TB_OBJETO.CD_OBJETO
     WHERE PA.SN_ATIVO = 'S' AND PA.TP_PERFIL = 'SIS'
)
SELECT /*+ PARALLEL(4) */ COUNT(1) AS TOTAL_DOCS_ORFAOS
  FROM EDITOR_DOCUMENTO ED
  LEFT JOIN PERFIL_DOC PD ON TO_CHAR(ED.CD_DOCUMENTO) = PD.CD_DOCUMENTO
 WHERE ED.CD_TIPO_ITEM = 13
   AND PD.CD_DOCUMENTO IS NULL;


