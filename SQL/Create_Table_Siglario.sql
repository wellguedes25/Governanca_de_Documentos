-- ==============================================================================
-- Tabela de Auditoria de Siglário (Medlytics Pro)
-- Finalidade: Rastrear ocorrências de siglas não padronizadas nos laudos.
-- Ambiente: Oracle Database (DBAMV)
-- ==============================================================================

CREATE TABLE DBAMV.TB_AUDITORIA_SIGLARIO (
    ID_AUDITORIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CD_ATENDIMENTO NUMBER NOT NULL,
    CD_DOCUMENTO NUMBER NOT NULL,
    CD_EDITOR_REGISTRO NUMBER NOT NULL,
    CD_DOCUMENTO_CLINICO NUMBER NOT NULL,
    SIGLA_DETECTADA VARCHAR2(100) NOT NULL,
    CONTEXTO VARCHAR2(500),
    DH_FECHAMENTO DATE NOT NULL,
    CD_PRESTADOR NUMBER,
    UNIDADE VARCHAR2(100),
    DH_AUDITORIA DATE DEFAULT SYSDATE NOT NULL
);

-- ==============================================================================
-- Comentários das Colunas
-- ==============================================================================
COMMENT ON TABLE DBAMV.TB_AUDITORIA_SIGLARIO IS 'Tabela que armazena os registros de infrações do dicionário (Siglário) gerados pela NLP via Python.';
COMMENT ON COLUMN DBAMV.TB_AUDITORIA_SIGLARIO.CD_ATENDIMENTO IS 'Código de Atendimento (Referência a DBAMV.ATENDIME)';
COMMENT ON COLUMN DBAMV.TB_AUDITORIA_SIGLARIO.CD_DOCUMENTO IS 'Código base do tipo de documento (EDITOR_DOCUMENTO)';
COMMENT ON COLUMN DBAMV.TB_AUDITORIA_SIGLARIO.CD_EDITOR_REGISTRO IS 'Link direto com a tabela filha para visualização do PDF / Print MV';
COMMENT ON COLUMN DBAMV.TB_AUDITORIA_SIGLARIO.CD_DOCUMENTO_CLINICO IS 'Chave da tabela PW_DOCUMENTO_CLINICO';
COMMENT ON COLUMN DBAMV.TB_AUDITORIA_SIGLARIO.SIGLA_DETECTADA IS 'O acrônimo fora de padrão que o motor encontrou (ex: pac.)';
COMMENT ON COLUMN DBAMV.TB_AUDITORIA_SIGLARIO.CONTEXTO IS 'Snippet limitando um pedaço da frase ao redor do acrônimo para contextualização rápida no painel sem precisar abrir o PDF';
COMMENT ON COLUMN DBAMV.TB_AUDITORIA_SIGLARIO.DH_FECHAMENTO IS 'Data de encerramento do documento que gerou a infração.';
COMMENT ON COLUMN DBAMV.TB_AUDITORIA_SIGLARIO.CD_PRESTADOR IS 'Código do Médico responsável pela quebra do Ouro.';
COMMENT ON COLUMN DBAMV.TB_AUDITORIA_SIGLARIO.UNIDADE IS 'Sigla do Setor (ex: UTI, PS).';
COMMENT ON COLUMN DBAMV.TB_AUDITORIA_SIGLARIO.DH_AUDITORIA IS 'Timestamp de quando o processamento em Python rodou sobre este laudo.';

-- ==============================================================================
-- Índices para Performance do Dashboard (React / Analytics)
-- ==============================================================================
CREATE INDEX DBAMV.IDX_SIGLARIO_DH ON DBAMV.TB_AUDITORIA_SIGLARIO(DH_FECHAMENTO);
CREATE INDEX DBAMV.IDX_SIGLARIO_TERMO ON DBAMV.TB_AUDITORIA_SIGLARIO(SIGLA_DETECTADA);
CREATE INDEX DBAMV.IDX_SIGLARIO_PRESTADOR ON DBAMV.TB_AUDITORIA_SIGLARIO(CD_PRESTADOR);
