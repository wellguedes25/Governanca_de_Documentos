-- Script para criação da View de Auditoria de Similaridade
-- Esta view prepara os dados para o processador Python de PLN

CREATE OR REPLACE VIEW DBAMV.V_AUDITORIA_COPIA_COLA AS
SELECT
    PDC.CD_ATENDIMENTO,
    PEC.CD_DOCUMENTO,
    PTD.DS_TIPO_DOCUMENTO AS DS_DOCUMENTO,
    ECA.DS_IDENTIFICADOR AS IDENTIFICADOR_FILTRO,
    PDC.DH_FECHAMENTO,
    PDC.CD_PRESTADOR AS CD_PRESTADOR,
    LEI.DS_RESUMO AS LEITO,
    UNI.DS_UNID_INT AS UNIDADE,
    DBMS_LOB.SUBSTR(ERC.LO_VALOR, 4000, 1) AS TEXTO_ATUAL,
    -- Captura o texto anterior (LAG) para o mesmo paciente e mesmo campo clínico
    LAG(DBMS_LOB.SUBSTR(ERC.LO_VALOR, 4000, 1)) OVER (
        PARTITION BY ATE.CD_PACIENTE, ECA.CD_CAMPO
        ORDER BY PDC.DH_FECHAMENTO
    ) AS TEXTO_ANTERIOR
FROM
    DBAMV.PW_DOCUMENTO_CLINICO PDC
INNER JOIN DBAMV.PW_TIPO_DOCUMENTO PTD ON PDC.CD_TIPO_DOCUMENTO = PTD.CD_TIPO_DOCUMENTO
INNER JOIN DBAMV.PW_EDITOR_CLINICO PEC ON PEC.CD_DOCUMENTO_CLINICO = PDC.CD_DOCUMENTO_CLINICO
INNER JOIN DBAMV.EDITOR_REGISTRO_CAMPO ERC ON ERC.CD_REGISTRO = PEC.CD_EDITOR_REGISTRO
INNER JOIN DBAMV.EDITOR_CAMPO ECA ON ECA.CD_CAMPO = ERC.CD_CAMPO
INNER JOIN DBAMV.ATENDIME ATE ON ATE.CD_ATENDIMENTO = PDC.CD_ATENDIMENTO
LEFT JOIN DBAMV.LEITO LEI ON ATE.CD_LEITO = LEI.CD_LEITO
LEFT JOIN DBAMV.UNID_INT UNI ON LEI.CD_UNID_INT = UNI.CD_UNID_INT
WHERE
    PDC.TP_STATUS IN ('FECHADO', 'ASSINADO')
    AND ERC.LO_VALOR IS NOT NULL;

-- Comentário: A view é genérica. O script Python ou a consulta podem filtrar por CD_DOCUMENTO específico.
