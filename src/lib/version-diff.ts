import { diffLines } from 'diff';
import type {
  BaseDiffItem,
  DiffChangeStatus,
  DiffCounts,
  FieldDiffItem,
  PropertyDelta,
  RuleDiffItem,
  SqlActionDiffItem,
  SqlDiffChunk,
  VersionFieldSnapshot,
  VersionRuleSnapshot,
  VersionSqlActionSnapshot,
} from '@/types/version-diff.types';

const STATUS_SORT_ORDER: Record<DiffChangeStatus, number> = {
  modified: 0,
  added: 1,
  removed: 2,
  unchanged: 3,
};

const VISUAL_TYPE_KEYWORDS = new Set([
  'LABEL',
  'ROTULO',
  'RÓTULO',
  'LINHA',
  'LINE',
  'PAINEL',
  'PANEL',
  'IMAGEM',
  'IMAGE',
  'SEPARADOR',
  'SEPARATOR',
  'SHAPE',
  'GROUPBOX',
  'FRAME',
  'TEXTO FIXO',
  'TEXTO_FIXO',
]);

const VISUAL_HASH_ID_REGEX =
  /^(label|lbl|panel|pnl|line|rect|box|group|frame|shape|image|img|separator|texto_fixo)_[A-Z0-9]{5,}$/i;

const AUTO_RULE_PREFIX_REGEX = /^(regra|rule|reg|r)_[A-Z0-9]{5,}$/i;
const UUID_REGEX =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const MIXED_HASH_TOKEN_REGEX = /^(?=.*\d)(?=.*[A-Z])[A-Z0-9]{6,}$/i;

/**
 * Normalizes SQL text to avoid false-positive diffs caused by CRLF vs LF
 * or trailing whitespace on lines.
 */
export function normalizeSql(sql?: string | null): string {
  if (!sql) return '';
  return String(sql)
    .replace(/\r\n/g, '\n')
    .replace(/\r/g, '\n')
    .split('\n')
    .map((line) => line.replace(/[ \t]+$/g, ''))
    .join('\n')
    .trim();
}

export function normalizeText(val?: string | number | null): string {
  if (val === null || val === undefined) return '';
  return String(val).trim();
}

/**
 * Identifies decorative/layout UI elements (e.g., Label, Panel, Line)
 * whose MV Editor 3.0 identifiers are regenerated as random hashes per version.
 */
export function isVisualField(f: VersionFieldSnapshot): boolean {
  const visualType = normalizeText(f.dsTipoVisualizacao).toUpperCase();
  if (VISUAL_TYPE_KEYWORDS.has(visualType)) {
    return true;
  }
  const identifier = normalizeText(f.dsIdentificador);
  return VISUAL_HASH_ID_REGEX.test(identifier);
}

/**
 * Identifies rule identifiers automatically generated by MV Editor 3.0
 * rather than meaningful human-authored names.
 */
export function isAutoGeneratedRuleId(id?: string | null): boolean {
  const trimmed = normalizeText(id);
  if (!trimmed) return true;
  if (/^\d+$/.test(trimmed)) return true;
  if (UUID_REGEX.test(trimmed)) return true;
  if (AUTO_RULE_PREFIX_REGEX.test(trimmed)) return true;
  if (!trimmed.includes('_') && MIXED_HASH_TOKEN_REGEX.test(trimmed)) return true;

  const parts = trimmed.split('_');
  const lastPart = parts[parts.length - 1] || '';
  if (parts.length >= 2 && MIXED_HASH_TOKEN_REGEX.test(lastPart) && lastPart.length >= 6) {
    return true;
  }

  return false;
}

/**
 * Extracts numeric document IDs referenced via CD_DOCUMENTO = N or CD_DOCUMENTO IN (...).
 */
export function extractReferencedDocs(script?: string | null): string[] {
  if (!script) return [];
  const refs = new Set<string>();

  const eqRegex = /\bCD_DOCUMENTO\s*=\s*(\d+)\b/gi;
  let match: RegExpExecArray | null = eqRegex.exec(script);
  while (match) {
    if (match[1]) refs.add(match[1]);
    match = eqRegex.exec(script);
  }

  const inRegex = /\bCD_DOCUMENTO\s+IN\s*\(([^)]+)\)/gi;
  let inMatch: RegExpExecArray | null = inRegex.exec(script);
  while (inMatch) {
    const inside = inMatch[1] || '';
    const nums = inside.match(/\d+/g);
    if (nums) {
      nums.forEach((n) => refs.add(n));
    }
    inMatch = inRegex.exec(script);
  }

  return Array.from(refs).sort((a, b) => Number(a) - Number(b));
}

/**
 * Pairs items by logical key (e.g., layout + identifier) rather than numeric PKs,
 * adding deterministic #2/#3 suffixes when duplicates exist in the same layout.
 */
export function buildUniqueKeyMap<T>(
  items: T[],
  getBaseKey: (item: T) => string
): Map<string, T> {
  const counts = new Map<string, number>();
  const result = new Map<string, T>();

  for (const item of items) {
    const rawKey = getBaseKey(item);
    const seen = (counts.get(rawKey) ?? 0) + 1;
    counts.set(rawKey, seen);
    const uniqueKey = seen === 1 ? rawKey : `${rawKey}#${seen}`;
    result.set(uniqueKey, item);
  }

  return result;
}

function buildLineDiff(beforeSql: string, afterSql: string): SqlDiffChunk[] {
  return diffLines(beforeSql, afterSql).map((part) => ({
    value: part.value,
    ...(part.added ? { added: true } : {}),
    ...(part.removed ? { removed: true } : {}),
  }));
}

function buildCounts<T>(items: BaseDiffItem<T>[]): DiffCounts {
  let added = 0;
  let removed = 0;
  let modified = 0;
  let unchanged = 0;

  for (const item of items) {
    if (item.status === 'added') added++;
    else if (item.status === 'removed') removed++;
    else if (item.status === 'modified') modified++;
    else unchanged++;
  }

  return {
    added,
    removed,
    modified,
    unchanged,
    totalChanged: added + removed + modified,
  };
}

function sortDiffItems<T extends BaseDiffItem<unknown>>(items: T[]): T[] {
  return [...items].sort((a, b) => {
    const statusDiff = STATUS_SORT_ORDER[a.status] - STATUS_SORT_ORDER[b.status];
    if (statusDiff !== 0) return statusDiff;
    if (a.layoutId !== b.layoutId) return a.layoutId - b.layoutId;
    return a.identifier.localeCompare(b.identifier, 'pt-BR');
  });
}

function buildVisualAliasMap(fields: VersionFieldSnapshot[]): Map<string, string> {
  const map = new Map<string, string>();
  for (const f of fields) {
    if (!isVisualField(f)) continue;
    const id = normalizeText(f.dsIdentificador);
    if (!id) continue;
    const labelText = normalizeText(f.dsCampo);
    const typeName = normalizeText(f.dsTipoVisualizacao) || 'Visual';
    map.set(id.toUpperCase(), `${typeName}("${labelText}")`);
  }
  return map;
}

function replaceVisualAliases(
  text: string | null | undefined,
  aliasMap?: Map<string, string>
): string {
  const normalized = normalizeText(text);
  if (!normalized || !aliasMap || aliasMap.size === 0) return normalized;

  return normalized.replace(/\b[A-Za-z0-9_]+\b/g, (token) => {
    const alias = aliasMap.get(token.toUpperCase());
    return alias ?? token;
  });
}

function formatRuleDisplayTitle(
  rule: VersionRuleSnapshot,
  normalizedCampos?: string,
  normalizedCondicao?: string
): string {
  const rawId = normalizeText(rule.dsRegra);
  if (!isAutoGeneratedRuleId(rawId) && rawId) {
    return rawId;
  }
  const typeLabel = normalizeText(rule.tipoRegra) || 'Regra';
  const targetHint =
    normalizeText(normalizedCampos || rule.camposAfetados) ||
    normalizeText(normalizedCondicao || rule.condicao) ||
    rawId ||
    `Regra #${rule.cdRegra}`;

  const compactHint =
    targetHint.length > 72 ? `${targetHint.slice(0, 69)}...` : targetHint;
  return `${typeLabel} → ${compactHint}`;
}

export function diffFields(
  baseItems: VersionFieldSnapshot[],
  targetItems: VersionFieldSnapshot[]
): FieldDiffItem[] {
  const keyOf = (f: VersionFieldSnapshot) => {
    if (isVisualField(f)) {
      const visualType = normalizeText(f.dsTipoVisualizacao).toUpperCase() || 'VISUAL';
      const labelText = normalizeText(f.dsCampo).toUpperCase();
      return `${f.cdTipoLayout}::VISUAL::${visualType}::${labelText || normalizeText(f.dsIdentificador).toUpperCase()}`;
    }
    return `${f.cdTipoLayout}::${normalizeText(f.dsIdentificador).toUpperCase() || `CAMPO_${f.cdCampo}`}`;
  };

  const baseMap = buildUniqueKeyMap(baseItems, keyOf);
  const targetMap = buildUniqueKeyMap(targetItems, keyOf);
  const allKeys = new Set<string>([...baseMap.keys(), ...targetMap.keys()]);
  const items: FieldDiffItem[] = [];

  for (const key of allKeys) {
    const base = baseMap.get(key) ?? null;
    const target = targetMap.get(key) ?? null;
    const sample = target ?? base!;
    const visual = isVisualField(sample);

    if (!base && target) {
      items.push({
        key,
        status: 'added',
        layoutId: target.cdTipoLayout,
        layoutName: target.dsTipoLayout,
        identifier: target.dsIdentificador || `CAMPO_${target.cdCampo}`,
        base: null,
        target,
        changes: [],
        isVisualElement: visual,
      });
      continue;
    }

    if (base && !target) {
      items.push({
        key,
        status: 'removed',
        layoutId: base.cdTipoLayout,
        layoutName: base.dsTipoLayout,
        identifier: base.dsIdentificador || `CAMPO_${base.cdCampo}`,
        base,
        target: null,
        changes: [],
        isVisualElement: visual,
      });
      continue;
    }

    if (base && target) {
      const changes: PropertyDelta[] = [];

      if (normalizeText(base.dsCampo) !== normalizeText(target.dsCampo)) {
        changes.push({
          field: 'dsCampo',
          label: 'Descrição',
          before: base.dsCampo || null,
          after: target.dsCampo || null,
        });
      }

      if (normalizeText(base.dsTipoVisualizacao) !== normalizeText(target.dsTipoVisualizacao)) {
        changes.push({
          field: 'dsTipoVisualizacao',
          label: 'Tipo de Componente',
          before: base.dsTipoVisualizacao || null,
          after: target.dsTipoVisualizacao || null,
        });
      }

      if (Number(base.snAtivo) !== Number(target.snAtivo)) {
        changes.push({
          field: 'snAtivo',
          label: 'Status',
          before: Number(base.snAtivo) === 1 ? 'Ativo' : 'Inativo',
          after: Number(target.snAtivo) === 1 ? 'Ativo' : 'Inativo',
        });
      }

      // Visual elements often share Meta #1 or regenerate transient IDs; avoid noisy metadata delta on unchanged labels
      if (!visual && (base.cdMetadado ?? null) !== (target.cdMetadado ?? null)) {
        changes.push({
          field: 'cdMetadado',
          label: 'Metadado ID',
          before: base.cdMetadado ?? null,
          after: target.cdMetadado ?? null,
        });
      }

      items.push({
        key,
        status: changes.length > 0 ? 'modified' : 'unchanged',
        layoutId: sample.cdTipoLayout,
        layoutName: sample.dsTipoLayout,
        identifier: sample.dsIdentificador || `CAMPO_${sample.cdCampo}`,
        base,
        target,
        changes,
        isVisualElement: visual,
      });
    }
  }

  return sortDiffItems(items);
}

interface NormalizedRuleEntry {
  rule: VersionRuleSnapshot;
  normTipo: string;
  normCondicao: string;
  normCampos: string;
  normAlerta: string;
  normScript: string;
  camposSet: Set<string>;
}

function normalizeRuleEntry(
  rule: VersionRuleSnapshot,
  aliasMap?: Map<string, string>
): NormalizedRuleEntry {
  const normTipo = normalizeText(rule.tipoRegra).toUpperCase();
  const normCondicao = replaceVisualAliases(rule.condicao, aliasMap);
  const normCampos = replaceVisualAliases(rule.camposAfetados, aliasMap);
  const normAlerta = normalizeText(rule.dsAlerta);
  const normScript = normalizeSql(rule.script);
  const camposSet = new Set(
    normCampos
      .split(',')
      .map((s) => s.trim().toUpperCase())
      .filter(Boolean)
  );

  return {
    rule,
    normTipo,
    normCondicao,
    normCampos,
    normAlerta,
    normScript,
    camposSet,
  };
}

function compareRuleEntries(
  key: string,
  baseEntry: NormalizedRuleEntry,
  targetEntry: NormalizedRuleEntry
): RuleDiffItem {
  const base = baseEntry.rule;
  const target = targetEntry.rule;
  const changes: PropertyDelta[] = [];

  if (Number(base.ativa) !== Number(target.ativa)) {
    changes.push({
      field: 'ativa',
      label: 'Status',
      before: Number(base.ativa) === 1 ? 'Ativa' : 'Inativa',
      after: Number(target.ativa) === 1 ? 'Ativa' : 'Inativa',
    });
  }

  if (baseEntry.normTipo !== targetEntry.normTipo) {
    changes.push({
      field: 'tipoRegra',
      label: 'Tipo de Regra',
      before: base.tipoRegra || null,
      after: target.tipoRegra || null,
    });
  }

  if ((base.numOrdem ?? null) !== (target.numOrdem ?? null)) {
    changes.push({
      field: 'numOrdem',
      label: 'Ordem',
      before: base.numOrdem ?? null,
      after: target.numOrdem ?? null,
    });
  }

  if (baseEntry.normAlerta !== targetEntry.normAlerta) {
    changes.push({
      field: 'dsAlerta',
      label: 'Mensagem / Alerta',
      before: base.dsAlerta || null,
      after: target.dsAlerta || null,
    });
  }

  if (baseEntry.normCondicao !== targetEntry.normCondicao) {
    changes.push({
      field: 'condicao',
      label: 'Condição',
      before: base.condicao || null,
      after: target.condicao || null,
    });
  }

  if (baseEntry.normCampos !== targetEntry.normCampos) {
    changes.push({
      field: 'camposAfetados',
      label: 'Campos Afetados',
      before: base.camposAfetados || null,
      after: target.camposAfetados || null,
    });
  }

  let scriptDiff: SqlDiffChunk[] | undefined;
  if (baseEntry.normScript !== targetEntry.normScript) {
    changes.push({
      field: 'script',
      label: 'Script SQL',
      before: baseEntry.normScript
        ? `${baseEntry.normScript.split('\n').length} linha(s)`
        : 'Sem script',
      after: targetEntry.normScript
        ? `${targetEntry.normScript.split('\n').length} linha(s)`
        : 'Sem script',
    });
    scriptDiff = buildLineDiff(baseEntry.normScript, targetEntry.normScript);
  }

  return {
    key,
    status: changes.length > 0 ? 'modified' : 'unchanged',
    layoutId: target.cdTipoLayout,
    layoutName: target.dsTipoLayout,
    identifier: target.dsRegra || `REGRA_${target.cdRegra}`,
    displayTitle: formatRuleDisplayTitle(
      target,
      targetEntry.normCampos,
      targetEntry.normCondicao
    ),
    base,
    target,
    changes,
    ...(scriptDiff ? { scriptDiff } : {}),
  };
}

function scoreRuleSimilarity(
  a: NormalizedRuleEntry,
  b: NormalizedRuleEntry
): number {
  if (a.rule.cdTipoLayout !== b.rule.cdTipoLayout) return 0;

  let score = 0;
  if (a.normTipo && a.normTipo === b.normTipo) score += 3;

  if (a.normCampos && a.normCampos === b.normCampos) {
    score += 4;
  } else if (a.camposSet.size > 0 && b.camposSet.size > 0) {
    let hasOverlap = false;
    for (const c of a.camposSet) {
      if (b.camposSet.has(c)) {
        hasOverlap = true;
        break;
      }
    }
    if (hasOverlap) score += 2;
  }

  if (a.normCondicao && a.normCondicao === b.normCondicao) score += 4;
  if (a.normAlerta && a.normAlerta === b.normAlerta) score += 2;
  if (a.normScript && a.normScript === b.normScript) score += 3;
  if (
    a.rule.numOrdem !== null &&
    b.rule.numOrdem !== null &&
    a.rule.numOrdem === b.rule.numOrdem
  ) {
    score += 1;
  }

  return score;
}

export function diffRules(
  baseItems: VersionRuleSnapshot[],
  targetItems: VersionRuleSnapshot[],
  baseAliasMap?: Map<string, string>,
  targetAliasMap?: Map<string, string>
): RuleDiffItem[] {
  const baseEntries = baseItems.map((r) => normalizeRuleEntry(r, baseAliasMap));
  const targetEntries = targetItems.map((r) => normalizeRuleEntry(r, targetAliasMap));

  const items: RuleDiffItem[] = [];
  const usedBase = new Set<number>();
  const usedTarget = new Set<number>();

  // Stage 1: Pair rules with meaningful human-authored DS_IDENTIFICADOR
  const humanKey = (e: NormalizedRuleEntry) =>
    `${e.rule.cdTipoLayout}::ID::${normalizeText(e.rule.dsRegra).toUpperCase()}`;

  const humanBase = buildUniqueKeyMap(
    baseEntries
      .map((entry, idx) => ({ entry, idx }))
      .filter((x) => !isAutoGeneratedRuleId(x.entry.rule.dsRegra)),
    (x) => humanKey(x.entry)
  );
  const humanTarget = buildUniqueKeyMap(
    targetEntries
      .map((entry, idx) => ({ entry, idx }))
      .filter((x) => !isAutoGeneratedRuleId(x.entry.rule.dsRegra)),
    (x) => humanKey(x.entry)
  );

  for (const [key, bPair] of humanBase.entries()) {
    const tPair = humanTarget.get(key);
    if (tPair) {
      usedBase.add(bPair.idx);
      usedTarget.add(tPair.idx);
      items.push(compareRuleEntries(key, bPair.entry, tPair.entry));
    }
  }

  // Stage 2: Exact content fingerprint pairing (ignores MV-regenerated DS_IDENTIFICADOR & numOrdem noise)
  const contentFingerprint = (e: NormalizedRuleEntry) =>
    `${e.rule.cdTipoLayout}::FP::${e.normTipo}|${Number(e.rule.ativa)}|${e.normCondicao}|${e.normCampos}|${e.normAlerta}|${e.normScript}`;

  const fpBase = buildUniqueKeyMap(
    baseEntries
      .map((entry, idx) => ({ entry, idx }))
      .filter((x) => !usedBase.has(x.idx)),
    (x) => contentFingerprint(x.entry)
  );
  const fpTarget = buildUniqueKeyMap(
    targetEntries
      .map((entry, idx) => ({ entry, idx }))
      .filter((x) => !usedTarget.has(x.idx)),
    (x) => contentFingerprint(x.entry)
  );

  for (const [key, bPair] of fpBase.entries()) {
    const tPair = fpTarget.get(key);
    if (tPair) {
      usedBase.add(bPair.idx);
      usedTarget.add(tPair.idx);
      items.push(compareRuleEntries(key, bPair.entry, tPair.entry));
    }
  }

  // Stage 3: Structural similarity pairing for modified rules whose DS_IDENTIFICADOR also changed
  const remainingBase = baseEntries
    .map((entry, idx) => ({ entry, idx }))
    .filter((x) => !usedBase.has(x.idx));
  const remainingTarget = targetEntries
    .map((entry, idx) => ({ entry, idx }))
    .filter((x) => !usedTarget.has(x.idx));

  const candidatePairs: Array<{ bIdx: number; tIdx: number; score: number }> = [];
  for (const b of remainingBase) {
    for (const t of remainingTarget) {
      const score = scoreRuleSimilarity(b.entry, t.entry);
      if (score >= 4) {
        candidatePairs.push({ bIdx: b.idx, tIdx: t.idx, score });
      }
    }
  }

  candidatePairs.sort((a, b) => b.score - a.score);
  for (const pair of candidatePairs) {
    if (usedBase.has(pair.bIdx) || usedTarget.has(pair.tIdx)) continue;
    usedBase.add(pair.bIdx);
    usedTarget.add(pair.tIdx);
    const bEntry = baseEntries[pair.bIdx];
    const tEntry = targetEntries[pair.tIdx];
    const key = `${tEntry.rule.cdTipoLayout}::SIM::${bEntry.rule.cdRegra}_${tEntry.rule.cdRegra}`;
    items.push(compareRuleEntries(key, bEntry, tEntry));
  }

  // Unpaired Base -> Removed
  for (const { entry, idx } of remainingBase) {
    if (usedBase.has(idx)) continue;
    const rule = entry.rule;
    items.push({
      key: `${rule.cdTipoLayout}::REM::${rule.cdRegra}_${idx}`,
      status: 'removed',
      layoutId: rule.cdTipoLayout,
      layoutName: rule.dsTipoLayout,
      identifier: rule.dsRegra || `REGRA_${rule.cdRegra}`,
      displayTitle: formatRuleDisplayTitle(
        rule,
        entry.normCampos,
        entry.normCondicao
      ),
      base: rule,
      target: null,
      changes: [],
      ...(entry.normScript ? { scriptDiff: buildLineDiff(entry.normScript, '') } : {}),
    });
  }

  // Unpaired Target -> Added
  for (const { entry, idx } of remainingTarget) {
    if (usedTarget.has(idx)) continue;
    const rule = entry.rule;
    items.push({
      key: `${rule.cdTipoLayout}::ADD::${rule.cdRegra}_${idx}`,
      status: 'added',
      layoutId: rule.cdTipoLayout,
      layoutName: rule.dsTipoLayout,
      identifier: rule.dsRegra || `REGRA_${rule.cdRegra}`,
      displayTitle: formatRuleDisplayTitle(
        rule,
        entry.normCampos,
        entry.normCondicao
      ),
      base: null,
      target: rule,
      changes: [],
      ...(entry.normScript ? { scriptDiff: buildLineDiff('', entry.normScript) } : {}),
    });
  }

  return sortDiffItems(items);
}

export function diffSqlActions(
  baseItems: VersionSqlActionSnapshot[],
  targetItems: VersionSqlActionSnapshot[]
): SqlActionDiffItem[] {
  const keyOf = (s: VersionSqlActionSnapshot) =>
    `${s.cdTipoLayout}::${normalizeText(s.dsIdentificador).toUpperCase() || `CAMPO_${s.cdCampo}`}::P${s.cdPropriedade}`;

  const baseMap = buildUniqueKeyMap(baseItems, keyOf);
  const targetMap = buildUniqueKeyMap(targetItems, keyOf);
  const allKeys = new Set<string>([...baseMap.keys(), ...targetMap.keys()]);
  const items: SqlActionDiffItem[] = [];

  for (const key of allKeys) {
    const base = baseMap.get(key) ?? null;
    const target = targetMap.get(key) ?? null;
    const sample = target ?? base!;

    if (!base && target) {
      const targetSql = normalizeSql(target.script);
      items.push({
        key,
        status: 'added',
        layoutId: target.cdTipoLayout,
        layoutName: target.dsTipoLayout,
        identifier: target.dsIdentificador || `CAMPO_${target.cdCampo}`,
        base: null,
        target,
        changes: [],
        scriptDiff: buildLineDiff('', targetSql),
      });
      continue;
    }

    if (base && !target) {
      const baseSql = normalizeSql(base.script);
      items.push({
        key,
        status: 'removed',
        layoutId: base.cdTipoLayout,
        layoutName: base.dsTipoLayout,
        identifier: base.dsIdentificador || `CAMPO_${base.cdCampo}`,
        base,
        target: null,
        changes: [],
        scriptDiff: buildLineDiff(baseSql, ''),
      });
      continue;
    }

    if (base && target) {
      const changes: PropertyDelta[] = [];

      if (normalizeText(base.nomeCampo) !== normalizeText(target.nomeCampo)) {
        changes.push({
          field: 'nomeCampo',
          label: 'Nome do Campo',
          before: base.nomeCampo || null,
          after: target.nomeCampo || null,
        });
      }

      if ((base.cdMetadado ?? null) !== (target.cdMetadado ?? null)) {
        changes.push({
          field: 'cdMetadado',
          label: 'Metadado ID',
          before: base.cdMetadado ?? null,
          after: target.cdMetadado ?? null,
        });
      }

      const normBaseSql = normalizeSql(base.script);
      const normTargetSql = normalizeSql(target.script);
      let scriptDiff: SqlDiffChunk[] | undefined;

      if (normBaseSql !== normTargetSql) {
        changes.push({
          field: 'script',
          label: 'Consulta SQL',
          before: `${normBaseSql.split('\n').length} linha(s)`,
          after: `${normTargetSql.split('\n').length} linha(s)`,
        });
        scriptDiff = buildLineDiff(normBaseSql, normTargetSql);
      }

      items.push({
        key,
        status: changes.length > 0 ? 'modified' : 'unchanged',
        layoutId: sample.cdTipoLayout,
        layoutName: sample.dsTipoLayout,
        identifier: sample.dsIdentificador || `CAMPO_${sample.cdCampo}`,
        base,
        target,
        changes,
        ...(scriptDiff ? { scriptDiff } : {}),
      });
    }
  }

  return sortDiffItems(items);
}

export function computeVersionDiff(input: {
  baseFields: VersionFieldSnapshot[];
  targetFields: VersionFieldSnapshot[];
  baseRules: VersionRuleSnapshot[];
  targetRules: VersionRuleSnapshot[];
  baseSqlActions: VersionSqlActionSnapshot[];
  targetSqlActions: VersionSqlActionSnapshot[];
}) {
  const fields = diffFields(input.baseFields, input.targetFields);
  const baseAliasMap = buildVisualAliasMap(input.baseFields);
  const targetAliasMap = buildVisualAliasMap(input.targetFields);
  const rules = diffRules(
    input.baseRules,
    input.targetRules,
    baseAliasMap,
    targetAliasMap
  );
  const sqlActions = diffSqlActions(input.baseSqlActions, input.targetSqlActions);

  const fieldsCounts = buildCounts(fields);
  const clinicalFieldItems = fields.filter((f) => !f.isVisualElement);
  const visualFieldItems = fields.filter((f) => f.isVisualElement);
  const clinicalFieldsCounts = buildCounts(clinicalFieldItems);
  const visualElementsChanged = visualFieldItems.filter(
    (f) => f.status !== 'unchanged'
  ).length;

  const rulesCounts = buildCounts(rules);
  const sqlActionsCounts = buildCounts(sqlActions);

  return {
    summary: {
      fields: fieldsCounts,
      clinicalFields: clinicalFieldsCounts,
      visualElementsCount: visualFieldItems.length,
      visualElementsChanged,
      rules: rulesCounts,
      sqlActions: sqlActionsCounts,
      totalChanges:
        clinicalFieldsCounts.totalChanged +
        rulesCounts.totalChanged +
        sqlActionsCounts.totalChanged,
    },
    fields,
    rules,
    sqlActions,
  };
}
